<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class ProductEditDraft extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | relation
        |--------------------------------------------------------------------------
        */
        'product_id',

        'shop_id',

        'created_by',

        /*
        |--------------------------------------------------------------------------
        | basic
        |--------------------------------------------------------------------------
        */
        'name',

        'description',

        'price',

        'shipping_fee',

        'stock',

        /*
        |--------------------------------------------------------------------------
        | images
        |--------------------------------------------------------------------------
        */
        'cover_img',

        'cover_img2',

        'cover_img3',

        /*
        |--------------------------------------------------------------------------
        | movie
        |--------------------------------------------------------------------------
        */
        'movie',

        'movie_file',

        /*
        |--------------------------------------------------------------------------
        | json
        |--------------------------------------------------------------------------
        */
        'product_attributes',

        /*
        |--------------------------------------------------------------------------
        | review
        |--------------------------------------------------------------------------
        */
        'status',

        'owner_comment',

        'approved_at',
    ];

    protected $casts = [

        'product_attributes' => 'array',

        'approved_at' => 'datetime',
    ];

    /*
    |--------------------------------------------------------------------------
    | relation
    |--------------------------------------------------------------------------
    */

    public function product()
    {
        return $this->belongsTo(
            Product::class
        );
    }

    public function shop()
    {
        return $this->belongsTo(
            Shop::class
        );
    }

    public function creator()
    {
        return $this->belongsTo(
            User::class,
            'created_by'
        );
    }
}
